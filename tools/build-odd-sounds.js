// Run:  node tools/build-odd-sounds.js
// Builds content/odd-sounds.js from content/odd-sounds.csv for the test "choose the word whose underlined part sounds different".
// CSV: header row, then  option 0,option 1,option 2,option 3,answer
//   - In each option, put the underlined letters between asterisks:  c*a*t,  *ch*air,  f*ir*st
//   - answer = the number of the odd option, counting from 0 (0, 1, 2 or 3).
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'content');
const text = fs.readFileSync(path.join(dir, 'odd-sounds.csv'), 'utf8').replace(/^﻿/, '');

function parseLine(line) {            // small CSV reader: commas, "quoted fields"
  const out = []; let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
    else if (ch === '"') q = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out.map(s => s.trim());
}

const lines = text.split(/\r?\n/).filter(l => l.trim());
const rows = [];
let problems = 0;
lines.slice(1).forEach((line, i) => {
  const n = i + 2, c = parseLine(line);
  const options = c.slice(0, 4), answer = Number(c[4]);
  if (options.length < 4 || options.some(o => !o)) { console.error('line ' + n + ': needs 4 options'); problems++; return; }
  if (!Number.isInteger(answer) || answer < 0 || answer > 3) { console.error('line ' + n + ': answer must be 0, 1, 2 or 3 (counting from 0)'); problems++; return; }
  const bad = options.findIndex(o => (o.match(/\*/g) || []).length < 2 || (o.match(/\*/g) || []).length % 2);
  if (bad > -1) { console.error('line ' + n + ': option ' + bad + ' ("' + options[bad] + '") needs the underlined letters between two asterisks'); problems++; return; }
  rows.push({ options, answer });
});

const body = rows.map(r => '  ' + JSON.stringify(r)).join(',\n');
fs.writeFileSync(path.join(dir, 'odd-sounds.js'),
  '/* GENERATED by tools/build-odd-sounds.js from content/odd-sounds.csv - do not edit by hand. Letters between * * are underlined; answer = number of the odd option (from 0). */\n' +
  'window.OEL = window.OEL || {};\nOEL.oddSounds = [\n' + body + '\n];\n');
console.log('content/odd-sounds.js written: ' + rows.length + ' questions' + (problems ? ', ' + problems + ' problem(s).' : '.'));
process.exit(problems ? 1 : 0);
