// Run:  node tools/split-questions.js
// Splits the question bank by CEFR level so the site only downloads the levels a page needs.
//   Reads:   content/questions.js          (the file you and your add-questions tool edit; keep it as it is)
//   Writes:  content/questionsA1.js ... content/questionsC2.js   and then content/manifest.js (via build-manifest.js)
// Every question keeps its position number from questions.js as "n", so the Admin page still tells you which line to fix.
// Run it again after every change to questions.js. Never edit the questionsXX.js files by hand.
const fs = require('fs'), path = require('path'), vm = require('vm'), cp = require('child_process');
const dir = path.join(__dirname, '..', 'content');
const LV = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
const src = fs.readFileSync(path.join(dir, 'questions.js'), 'utf8');

const sb = { console }; sb.window = sb; vm.createContext(sb); vm.runInContext(src, sb);
const total = (sb.OEL.questions || []).length;

// Cut the text of every top-level { ... } inside OEL.questions = [ ... ]; (some questions span several lines).
// The scan understands strings and // and /* */ comments, so braces inside text cannot confuse it.
const objs = [];
{
  let i = src.indexOf('[', src.indexOf('OEL.questions')), depth = 0, start = -1, str = null;
  for (i = i + 1; i < src.length; i++) {
    const c = src[i];
    if (str) { if (c === '\\') i++; else if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === '`') { str = c; continue; }
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i) + 1; continue; }
    if (c === '{' || c === '[') { if (depth === 0 && c === '{') start = i; depth++; }
    else if (c === '}' || c === ']') { if (depth === 0) break; depth--; if (depth === 0 && c === '}') objs.push(src.slice(start, i + 1)); }
  }
}
if (objs.length !== total) { console.error('ERROR: found ' + objs.length + ' question objects but questions.js holds ' + total + ' questions. Nothing written.'); process.exit(1); }
const parts = Object.fromEntries(LV.map(l => [l, []]));
let bad = 0;
sb.OEL.questions.forEach((q, i) => {
  const l = String(q && q.level).toUpperCase();
  if (!parts[l]) { bad++; console.error('ERROR: question #' + (i + 1) + ' has level "' + (q && q.level) + '" (must be A1, A2, B1, B2, C1 or C2)'); return; }
  parts[l].push('  { n: ' + (i + 1) + ', ' + objs[i].replace(/^\{\s*/, ''));
});
if (bad) { console.error('Nothing written.'); process.exit(1); }

const counts = {};
LV.forEach(l => {
  const body = parts[l].join(',\n');
  const out = '/* GENERATED by tools/split-questions.js from content/questions.js - do not edit by hand. Questions of level ' + l + '; n = position in questions.js. */\n' +
    'window.OEL = window.OEL || {};\nOEL.qparts = OEL.qparts || {};\nOEL.qparts.' + l + ' = [\n' + body + '\n];\n';
  fs.writeFileSync(path.join(dir, 'questions' + l + '.js'), out);
  counts[l] = parts[l].length;
});

// Check: the pieces together are exactly the original questions.
const sb2 = { console }; sb2.window = sb2; vm.createContext(sb2);
LV.forEach(l => vm.runInContext(fs.readFileSync(path.join(dir, 'questions' + l + '.js'), 'utf8'), sb2));
const back = [];
LV.forEach(l => sb2.OEL.qparts[l].forEach(q => back[q.n - 1] = q));
let diff = 0;
sb.OEL.questions.forEach((q, i) => { const b = Object.assign({}, back[i]); delete b.n; if (JSON.stringify(b) !== JSON.stringify(q)) diff++; });
if (diff) { console.error('ERROR: ' + diff + ' question(s) differ after the split. Do not publish.'); process.exit(1); }
console.log('Split ' + total + ' questions: ' + LV.map(l => l + ' ' + counts[l]).join(', ') + '. Check passed.');
cp.execFileSync('node', [path.join(__dirname, 'build-manifest.js')], { stdio: 'inherit' });
