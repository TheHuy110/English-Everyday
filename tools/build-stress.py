#!/usr/bin/env python3
"""Builds content/stress.js: the words of the vocabulary list grouped by syllable count and position of the main stress.

Run:  pip install cmudict   then   python3 tools/build-stress.py
Used by the IPA test "choose the word with a different stress pattern". Stress comes from the CMU Pronouncing Dictionary
(it counts syllables correctly, including syllabic l/n) and is cross-checked against the Oxford phonetics in content/vocab.js.
A word is left out when the dictionary has several pronunciations that disagree, or when it disagrees with Oxford.
Output key "n:p" = n syllables, main stress on syllable p (0 = first).
"""
import json, os, re, sys
import cmudict

HERE = os.path.dirname(os.path.abspath(__file__))
VOCAB = os.path.join(HERE, '..', 'content', 'vocab.js')
OUT = os.path.join(HERE, '..', 'content', 'stress.js')
D = cmudict.dict()
VOW = re.compile(r'aɪ|aʊ|eɪ|ɔɪ|əʊ|oʊ|ɜː|[aiɪeæɑɔʊuʌə]ː?')

def cmu_pattern(word):
    prons = D.get(word)
    if not prons: return None
    seen = set()
    for ph in prons:
        digits = ''.join(p[-1] for p in ph if p[-1].isdigit())
        if digits.count('1') != 1: return None
        seen.add((len(digits), digits.index('1')))
    return seen.pop() if len(seen) == 1 else None      # variants that disagree: skip the word

def oxford_primary(ph):
    ph = ph.strip('/')
    if ph.count('ˈ') != 1: return None
    pos = ph.index('ˈ')
    return sum(1 for m in VOW.finditer(ph) if m.start() < pos)

def main():
    src = open(VOCAB, encoding='utf-8').read()
    rows = json.loads(src[src.index('[\n') if '[\n' in src else src.index('['):src.rindex(']') + 1])
    by_word = {}
    for r in rows:
        w = str(r[1]).lower()
        if not re.fullmatch(r'[a-z]{3,}', w) or not r[4] or ' ' in r[4]: continue
        by_word.setdefault(w, []).append(r[4])
    groups, dropped = {}, 0
    for w, phs in by_word.items():
        pat = cmu_pattern(w)
        if not pat or not (2 <= pat[0] <= 4): continue
        if any(oxford_primary(ph) != pat[1] for ph in phs): dropped += 1; continue
        groups.setdefault('%d:%d' % pat, []).append(w)
    keys = sorted(groups)
    body = ',\n'.join('  ' + json.dumps(k) + ': ' + json.dumps(sorted(groups[k]), ensure_ascii=False) for k in keys)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('/* GENERATED by tools/build-stress.py - do not edit by hand. Words grouped by "syllables:index of the stressed syllable". */\n'
                'window.OEL = window.OEL || {};\nOEL.stress = {\n' + body + '\n};\n')
    print('content/stress.js written.', ', '.join('%s=%d' % (k, len(groups[k])) for k in keys), '| dropped (CMU and Oxford disagree):', dropped)

if __name__ == '__main__':
    sys.exit(main())
