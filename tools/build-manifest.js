// Run:  node tools/build-manifest.js
// Writes content/manifest.js: the item counts the home page and journal show before the big content files are downloaded.
// Run it again whenever you change grammar.js, questions.js, tests.js, ipa.js or the vocabulary files.
const fs = require('fs'), path = require('path'), vm = require('vm');
const dir = path.join(__dirname, '..', 'content');
const LV = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
const list = x => Array.isArray(x) ? x : [];
const str = x => typeof x === 'string' ? x.trim() : '';

function compute() {
const sandbox = { console }; sandbox.window = sandbox; vm.createContext(sandbox);
for (const f of ['grammar', 'questions', 'tests', 'ipa', 'vocab']) {
  try { vm.runInContext(fs.readFileSync(path.join(dir, f + '.js'), 'utf8'), sandbox, { filename: f + '.js' }); }
  catch (e) { console.error('ERROR: content/' + f + '.js cannot be loaded: ' + e.message); process.exit(1); }
}
const OEL = sandbox.OEL || {};
// The same rules app.js uses to skip broken entries, so the numbers match what the site shows.
const grammar = list(OEL.grammar).filter(g => g && str(g.title) && str(g.level) && str(g.rule));
const grammarByLevel = {};
grammar.forEach(g => { const l = str(g.level).toUpperCase(); grammarByLevel[l] = (grammarByLevel[l] || 0) + 1; });

const questions = list(OEL.questions).filter(q => {
  if (!q || !q.question || !str(q.level)) return false;
  const o = list(q.options).map(String);
  return o.length >= 2 && o.indexOf(String(q.answer)) > -1;
});

const ipa = list(OEL.ipa && OEL.ipa.sounds).filter(s => s && str(s.id) && str(s.symbol));

const seen = {}, orders = {};
let vocab = 0;
list(OEL.vocab).forEach(r => {
  if (!Array.isArray(r) || !str(r[1]) || LV.indexOf(str(r[3]).toUpperCase()) < 0) return;
  orders[r[0]] = 1;
  let id = String(r[1]) + '|' + String(r[2] || '');
  if (seen[id]) id += '|' + r[0];
  if (seen[id]) return;
  seen[id] = 1; vocab++;
});

const ids = {};
const sets = list(OEL.tests).filter(s => {
  if (!s || !str(s.id) || !str(s.title) || ids[str(s.id)]) return false;
  const lvs = list(s.levels).map(l => String(l).toUpperCase());
  const ok = questions.some(q => lvs.indexOf(str(q.level).toUpperCase()) > -1);
  if (ok) ids[str(s.id)] = 1;
  return ok;
}).length;

return { grammar: grammar.length, grammarByLevel, questions: questions.length, vocab, ipa: ipa.length, sets };
}
module.exports = { compute };
if (require.main === module) {
const manifest = compute();
const out = '/* GENERATED by tools/build-manifest.js - do not edit by hand. Item counts shown before the big content files are loaded. */\n' +
  'window.OEL = window.OEL || {};\nOEL.manifest = ' + JSON.stringify(manifest) + ';\n';
fs.writeFileSync(path.join(dir, 'manifest.js'), out);
console.log('content/manifest.js written:', JSON.stringify(manifest));
}
